export const IMX6ULL_BALL_PITCH = 0.8

// Rank-one controls, A15, ZQ calibration and VREF are not connected to the
// single-rank 4 Gb x16 fixture. Their physical pads remain obstacles.
const unusedDramSignals = new Set([
  "DRAM_ODT1",
  "DRAM_CS1_B",
  "DRAM_SDCKE1",
  "DRAM_ADDR15",
  "DRAM_ZQPAD",
  "DRAM_VREF",
])
export const IMX6ULL_DDR_SIGNAL_BALL_MAP = Object.fromEntries(
  Object.entries(IMX6ULL_BALL_MAP).filter(
    ([, signal]) =>
      signal.startsWith("DRAM_") && !unusedDramSignals.has(signal),
  ),
)
export const IMX6ULL_VSS_BALL_NAMES = Object.keys(IMX6ULL_BALL_MAP).filter(
  (ball) => IMX6ULL_BALL_MAP[ball] === "VSS",
)
export const IMX6ULL_DDR_VDD_BALL_NAMES = Object.keys(IMX6ULL_BALL_MAP).filter(
  (ball) => IMX6ULL_BALL_MAP[ball] === "NVCC_DRAM",
)
