export const AM3352_NC_BALLS = ["A3", "M5"] as const
export const AM3352_PINS = AM3352_ROW_NAMES.flatMap((row, rowIndex) =>
  Array.from({ length: 18 }, (_, columnIndex) => {
    const ballName = `${row}${columnIndex + 1}`
    return {
      pinNumber: rowIndex * 18 + columnIndex + 1,
      ballName,
      name: AM3352_BALL_MAP[ballName]!,
      x: Number(((columnIndex - 8.5) * AM3352_BALL_PITCH).toFixed(3)),
      y: Number(((8.5 - rowIndex) * AM3352_BALL_PITCH).toFixed(3)),
    }
  }),
)
export function getAm3352Pin(pinNumber: number) {
  const pin = AM3352_PINS[pinNumber - 1]
  if (!pin) throw new Error(`Unknown AM3352 pin ${pinNumber}`)
  return pin
}
